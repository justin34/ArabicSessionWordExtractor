import { mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { isArabicWord } from './analysis/align';
import { AnkiExporter } from './anki/export';
import { ApiKeys, type ApiKeysOptions } from './apiKeys';
import { WordDetailsBuilder, type DetailModuleConfig } from './details/wordDetails';
import { StudyGuides } from './guides/studyGuides';
import type { Providers } from './providers';
import { MicTranscriptions } from './micTranscription';
import { Sessions } from './sessions';
import { Settings, type SecretCodec } from './settings';
import { Store } from './store';
import type { AnkiExportTarget, SessionGuide, VocabularyEntry, WordCard, WordDetails } from './types';

/** The Vocabulary, built by the Session pipeline as Utterances are analyzed. */
export interface Vocabulary {
  list(): VocabularyEntry[];
}

/** The click-a-word panel's content. */
export interface Words {
  /** The Detail Module sections for a Lemma; `surface` is the form clicked. */
  details(lemmaId: number, surface?: string): Promise<WordDetails | undefined>;
}

/** Word Cards and Session Guides, generated by the Session pipeline. */
export interface Guides {
  wordCard(lemmaId: number): WordCard | undefined;
  sessionGuide(sessionId: number): SessionGuide | undefined;
  /** Settles once Word Cards rebuilt in the background are all stored. */
  idle(): Promise<void>;
}

/** "Export to Anki" (GLOSSARY: Anki export): one-way, and nothing is recorded about it. */
export interface Anki {
  /** The Save dialog's suggested file name. */
  defaultFileName(target: AnkiExportTarget): string;
  /** Writes the `.apkg` to `path`, whole or not at all; returns how many words it holds. */
  export(target: AnkiExportTarget, path: string): Promise<number>;
}

export interface App {
  sessions: Sessions;
  /** "Transcribe my microphone" for completed Sessions, in the background. */
  micTranscriptions: MicTranscriptions;
  vocabulary: Vocabulary;
  words: Words;
  guides: Guides;
  anki: Anki;
  /** Stored settings, e.g. which audio devices to record from. */
  settings: Settings;
  /** The API keys in use, from Settings or the environment, and their checks. */
  apiKeys: ApiKeys;
  /** Closes storage. Word Cards still being rebuilt are left as they were; wait for `guides.idle()` to finish them. */
  close(): void;
}

export interface AppOptions {
  dataDir: string;
  /** The providers, or a builder given the API keys (for the keyed speech-to-text and translator). */
  providers: Providers | ((keys: ApiKeys) => Providers);
  /** How API keys are kept in `settings.json`; as entered by default. */
  secrets?: SecretCodec;
  /** Environment fallback for API keys, and the key checks' fetch. */
  keys?: ApiKeysOptions;
  /** Detail Modules for the word panel and Word Cards, in order; all built-ins by default. */
  detailModules?: DetailModuleConfig;
  /** How long analysis waits for an Utterance's translation; 3 s by default. */
  translationWaitMs?: number;
  /** The Arabic font packaged with Anki exports, when it exists. */
  ankiFontPath?: string;
}

/** Wires local storage and the providers into the Session pipeline. */
export function createApp({
  dataDir,
  providers: given,
  secrets,
  keys,
  detailModules,
  translationWaitMs,
  ankiFontPath,
}: AppOptions): App {
  mkdirSync(dataDir, { recursive: true });
  const settings = new Settings(join(dataDir, 'settings.json'), secrets);
  const apiKeys = new ApiKeys(settings, keys);
  const providers = typeof given === 'function' ? given(apiKeys) : given;
  const store = new Store(join(dataDir, 'app.db'));
  // Foreign words stored before they were kept out of the Vocabulary leave it now.
  store.removeForeignWords(isArabicWord);
  const builder = new WordDetailsBuilder(store, { store, dictionary: providers.dictionary }, detailModules);
  const studyGuides = new StudyGuides(store, builder);
  const recordingsDir = join(dataDir, 'recordings');
  const sessions = new Sessions(store, providers, recordingsDir, studyGuides, {
    translationWaitMs,
  });
  const micTranscriptions = new MicTranscriptions(store, providers, recordingsDir);
  // Sessions a crash ended, and data from before study guides, get theirs now.
  studyGuides.catchUp();
  const vocabulary: Vocabulary = { list: () => store.listVocabulary() };
  const words: Words = { details: (lemmaId, surface) => builder.details(lemmaId, surface) };
  const guides: Guides = {
    wordCard: (lemmaId) => studyGuides.wordCard(lemmaId),
    sessionGuide: (sessionId) => studyGuides.sessionGuide(sessionId),
    idle: () => studyGuides.idle(),
  };
  const exporter = new AnkiExporter(store, providers.dictionary, { fontPath: ankiFontPath });
  const anki: Anki = {
    defaultFileName: (target) => exporter.defaultFileName(target),
    export: (target, path) => exporter.export(target, path),
  };
  const close = () => {
    studyGuides.stop();
    store.close();
  };
  return { sessions, micTranscriptions, vocabulary, words, guides, anki, settings, apiKeys, close };
}
